// harm in its own lines.
// The same lines serve the pond and, later, a glass jar, so they name the water, the pad, the rock and
// the glass or the edge, and fireflies only at night; nothing that is true of one home alone.
// `{name}` is the pet's own name. Keep each line short enough for the bubble (about 90 characters).

